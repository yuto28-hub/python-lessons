# 1から100までの合計を計算して表示するプログラム

def main():
    # 合計を入れておく箱を用意する（最初は0）
    total = 0

    # range(1, 101) は 1, 2, 3, ... , 100 という数字の並びを作る
    # 「101」なのは、range は終わりの数を含まないため
    for i in range(1, 101):
        total = total + i  # total に i を足していく

    # 計算結果を表示する
    print("1から100までの合計:", total)


# このファイルを直接実行したときだけ main() を動かすおまじない
if __name__ == "__main__":
    main()
